#!/usr/bin/env bash
#
# Embeds a subset of Maple Mono into keymap_drawer.config.yaml as a base64
# @font-face, so the keymap diagram renders in the same font everywhere.
#
# An SVG shown through GitHub's image proxy cannot fetch anything external, so
# the font has to travel inside the file. Subsetting keeps that affordable:
# ~7 KB per weight instead of ~75 KB.
#
# Maple Mono is licensed under the SIL Open Font License 1.1, which permits
# embedding. https://github.com/subframe7536/maple-font
#
# Requires: curl, unzip, uv. Re-run to bump FONT_VERSION.

set -euo pipefail

FONT_VERSION="v7.9"
CONFIG="keymap_drawer.config.yaml"

# Printable ASCII plus the arrows and symbols keymap-drawer emits for keycodes.
# Deliberately wider than what the current keymap uses, so adding a key cannot
# silently produce tofu in CI.
UNICODES="U+0020-007E,U+00A0,U+00B0,U+00D7,U+2010-2015,U+2018-201D"
UNICODES+=",U+2190-2193,U+21B5,U+21E7,U+2303,U+2318,U+2325,U+23CE,U+2423"
UNICODES+=",U+25B3,U+25BD,U+2713,U+2717"

cd "$(dirname "$0")/.."
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

echo "Downloading Maple Mono $FONT_VERSION..."
curl -sSL -o "$work/maple.zip" \
  "https://github.com/subframe7536/maple-font/releases/download/$FONT_VERSION/MapleMono-Woff2.zip"
unzip -q -o "$work/maple.zip" -d "$work/maple"

for weight in Regular Bold; do
  echo "Subsetting $weight..."
  uvx --with brotli --from fonttools pyftsubset \
    "$work/maple/MapleMono-$weight.ttf.woff2" \
    --unicodes="$UNICODES" --flavor=woff2 --layout-features='' \
    --output-file="$work/$weight.woff2"
done

echo "Rewriting $CONFIG..."
FONT_VERSION="$FONT_VERSION" WORK="$work" CONFIG="$CONFIG" python3 - <<'PY'
import base64, os, re

work, config, version = os.environ["WORK"], os.environ["CONFIG"], os.environ["FONT_VERSION"]
pad = " " * 4

faces = []
for weight, css_weight in (("Regular", 400), ("Bold", 700)):
    b64 = base64.b64encode(open(f"{work}/{weight}.woff2", "rb").read()).decode()
    faces.append(
        f'{pad}@font-face {{ font-family: "Maple Mono"; font-style: normal; '
        f"font-weight: {css_weight}; src: url(data:font/woff2;base64,{b64}) "
        f'format("woff2"); }}'
    )

block = "\n".join([
    f"{pad}/* --- BEGIN EMBEDDED FONT: Maple Mono {version}, SIL OFL 1.1. -----------",
    f"{pad}   Generated by bin/embed-keymap-font.sh; edit that, not this. --------- */",
    *faces,
    f"{pad}/* --- END EMBEDDED FONT --- */",
])

text = open(config).read()
pattern = re.compile(
    rf"^{pad}/\* --- BEGIN EMBEDDED FONT.*?^{pad}/\* --- END EMBEDDED FONT --- \*/$",
    re.S | re.M,
)
if pattern.search(text):
    text = pattern.sub(lambda _: block, text)
else:
    text = text.rstrip("\n") + "\n\n" + block + "\n"
open(config, "w").write(text)
PY

echo "Done. $(wc -c < "$CONFIG" | tr -d ' ') bytes."
